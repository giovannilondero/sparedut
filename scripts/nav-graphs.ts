/**
 * Precomputes the bot graphs of every map into `server/nav-graphs.ts`: they cost tens of
 * seconds of CPU, which the server shouldn't spend on every start (on Cloudflare, on every wake-up).
 * Rerun when a map, movement or physics changes: `pnpm nav`.
 */
import { MAP_IDS, MAPS } from "../shared/maps/index.ts"
import { createPhysicsWorld, initPhysics } from "../shared/physics.ts"
import { computeNavGraph, mapFingerprint } from "../server/nav.ts"

await initPhysics()
const lines: string[] = []
for (const id of MAP_IDS) {
  const started = performance.now()
  const { edges } = computeNavGraph(createPhysicsWorld(MAPS[id]))
  console.log(`🧭 ${id}: ${edges.length} points in ${Math.round(performance.now() - started)} ms`)
  lines.push(`  ${id}: { map: "${mapFingerprint(MAPS[id])}", edges: ${JSON.stringify(edges)} },`)
}

const source = `// Generated by \`pnpm nav\` (scripts/nav-graphs.ts): do not edit by hand.
import type { MapId } from "../shared/map.ts"

/** For each map, the edges of the bot graph and the fingerprint of the map they come from. */
export const NAV_GRAPHS: Partial<Record<MapId, { readonly map: string; readonly edges: number[][] }>> = {
${lines.join("\n")}
}
`
await Bun.write(new URL("../server/nav-graphs.ts", import.meta.url), source)
